import assert from 'node:assert/strict';
import {clampPersonBox,boxIoU,chooseTrackedPerson,actorBoxAt,drawActorCrop} from '../../docs/assets/projects/video-action/browser-inference/person-target.js';
const box=(x,y,w,h)=>({originX:x,originY:y,width:w,height:h});
const person=(b,score=.9)=>({boundingBox:b,categories:[{categoryName:'person',score}]});
const original=box(40,20,50,150),other=box(220,40,110,130);
assert.deepEqual(chooseTrackedPerson([person(original)],400,200,null),original);
assert.deepEqual(chooseTrackedPerson([person(other),person(box(43,23,53,145))],400,200,original),box(43,23,53,145));
assert.equal(chooseTrackedPerson([person(other)],400,200,original),null,'must never switch to unrelated actor');
assert.ok(boxIoU(original,box(43,23,53,145))>.7);
assert.equal(actorBoxAt([{t:0,box:original},{t:.5,box:null},{t:1,box:other}],.7),null);
assert.deepEqual(actorBoxAt([{t:0,box:original},{t:.5,box:original}],.75),original);
assert.equal(actorBoxAt([{t:0,box:original}],2),null);
assert.equal(clampPersonBox(box(-5,-1,410,300),400,200).width,400);
let cropped=null,painted=0;
const ctx={clearRect(){},fillRect(){painted++},set fillStyle(x){},drawImage(...args){cropped=args}};
const video={videoWidth:400,videoHeight:200};
drawActorCrop(ctx,video,original,224);
assert.equal(painted,1);
assert.equal(cropped[0],video);
assert.ok(cropped[3]<video.videoWidth&&cropped[4]<video.videoHeight,'must use actor ROI, not entire frame');
assert.throws(()=>drawActorCrop(ctx,video,null,224),/没有已跟踪的人物框/);
console.log('PASS actor selection continuity, no identity switch, missing track, actual ROI crop');
