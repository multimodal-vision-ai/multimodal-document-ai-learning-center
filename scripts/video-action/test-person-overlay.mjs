import assert from 'node:assert/strict';
import {choosePrimaryPerson,mapBoxToContainedVideo,top1At} from '../../docs/assets/projects/video-action/browser-inference/person-overlay.js';
const person=(box,score=.8)=>({boundingBox:box,categories:[{categoryName:'person',score}]});
const dog={boundingBox:{originX:0,originY:0,width:100,height:100},categories:[{categoryName:'dog',score:.9}]};
const smaller=person({originX:12,originY:10,width:40,height:100},.9);
const larger=person({originX:60,originY:15,width:150,height:210},.65);
let found=choosePrimaryPerson([smaller,dog,larger],300,300);
assert.equal(found.candidateCount,2);
assert.equal(found.person,larger,'Must select larger visible person, not higher object score');
assert.equal(choosePrimaryPerson([dog],300,300).person,null);
const portrait={originX:100,originY:110,width:130,height:350};
const mapped=mapBoxToContainedVideo(portrait,360,640,960,540);
assert.ok(mapped,'Must map portrait video to letterboxed 16:9 player');
const scale=540/640,xoff=(960-360*scale)/2;
assert.ok(Math.abs(mapped.x-(xoff+100*scale))<.001);
assert.ok(Math.abs(mapped.y-110*scale)<.001);
assert.ok(mapped.x>320,'Portrait video detection must be inside actual letterbox region, not black pillar bars');
const nearEdge=mapBoxToContainedVideo({originX:-10,originY:-10,width:100,height:100},200,200,200,200);
assert.deepEqual(nearEdge,{x:0,y:0,w:90,h:90},'Clamp coordinates to display');
assert.equal(mapBoxToContainedVideo(null,0,0,0,0),null);
const timeline=[{t:0,id:1,label:'a',score:.3},{t:.2,id:2,label:'b',score:.6},{t:.4,id:3,label:'c',score:.8}];
assert.equal(top1At(timeline,.21,.4).label,'b');
assert.equal(top1At(timeline,.45,.4),null,'Never show fabricated labels beyond analyzed time');
assert.equal(top1At([],0,.4),null);
console.log('PASS: person selection, portrait letterbox geometry, clipping and verified-time Top1 timeline');
