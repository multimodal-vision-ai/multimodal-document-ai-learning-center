import assert from 'node:assert/strict';
import {MOBILECLIP,MOBILECLIP_LABELS,MOBILECLIP_PROMPTS,aggregateMobileCLIPScores,normalizeMobileCLIPResult,mobileCLIPReferenceRank,inferMobileCLIP} from '../../docs/assets/projects/video-action/browser-inference/mobileclip.js';
assert.equal(MOBILECLIP.frameCount,6);
assert.equal(new Set(MOBILECLIP_LABELS).size,6);
assert.equal(new Set(MOBILECLIP_PROMPTS).size,6);
const a=[0.50,0.10,0.10,0.10,0.10,0.10],b=[0.10,0.50,0.10,0.10,0.10,0.10];
const avg=aggregateMobileCLIPScores([a,b]);
assert.ok(Math.abs(avg[0]-.30)<1e-6);
assert.ok(Math.abs(avg.reduce((x,y)=>x+y,0)-1)<1e-6);
assert.deepEqual(normalizeMobileCLIPResult([...MOBILECLIP_PROMPTS].reverse().map((label,index)=>({label,score:0.1+0.02*index}))).length,6);
assert.equal(mobileCLIPReferenceRank([.1,.5,.1,.1,.1,.1],{standard_action_id:'phone_use'}),1);
assert.equal(mobileCLIPReferenceRank([.5,.1,.1,.1,.1,.1],{standard_action_id:'phone_call'}),3);
assert.equal(mobileCLIPReferenceRank(avg,null),null);
assert.throws(()=>aggregateMobileCLIPScores([]),/没有有效/);
assert.throws(()=>normalizeMobileCLIPResult([{label:'unknown',score:1}]),/六个候选/);
const mockFrame={};
let calls=0;
const classifier=async(frame,prompts)=>{
 assert.equal(frame,mockFrame);
 assert.equal(prompts.length,6);
 calls++;
 return prompts.map((label,i)=>({label,score:i===1?0.8:0.04}));
};
const result=await inferMobileCLIP({classifier,frames:Array(6).fill(mockFrame)});
assert.equal(calls,6);
assert.equal(result.frameCount,6);
assert.ok(result.scores[1]>.79);
assert.ok(Math.abs(result.scores.reduce((x,y)=>x+y,0)-1)<1e-5);
await assert.rejects(()=>inferMobileCLIP({classifier,frames:[]}),/关键帧数量/);
console.log('PASS MobileCLIP semantics, six real-call contract, reference rank, closed-set normalization');
