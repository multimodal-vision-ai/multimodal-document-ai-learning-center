EFFICIENCY_TERMS = (
    "efficient", "efficiency", "distillation", "distill", "quantization",
    "quantized", "low-bit", "token compression", "token reduction",
    "pruning", "lora", "qlora", "on-device", "edge deployment",
    "dynamic resolution", "memory efficient", "parameter-efficient",
)
ARTIFACT_TERMS = ("benchmark", "dataset", "evaluation", "benchmarking", "leaderboard")
NOISE_TERMS = (
    "generateddigitalexps", "placeholder", "dummy-repo", "tmp-repo",
    "syntheticrandom", "autogenerated-test",
)


def _date(value):
    try:
        return parse_dt(value) if value else None
    except (TypeError, ValueError, OverflowError):
        return None


def _in_window(value, since, until):
    return value is not None and since <= value <= until


def candidate_event(item, since, until):
    """Return a defensible event date/label for this provider and time window."""
    provider = str(item.get("discovered_from") or "").lower()
    published = _date(item.get("published_at"))
    updated = _date(item.get("updated_at"))

    if provider == "arxiv":
        if _in_window(published, since, until):
            return {
                "event_at": published.isoformat(timespec="seconds"),
                "event_label": "新论文 / 新投稿",
                "is_new_paper": True,
            }
        # Only call an older arXiv record a version update when the canonical
        # URL itself identifies a newer version (v2, v3, ...). A timestamp alone
        # is not enough evidence of a substantive update.
        import re
        version = re.search(r"v(\d+)(?:$|[?#])", str(item.get("source_url") or ""))
        has_new_version = bool(version and int(version.group(1)) > 1)
        if (_in_window(updated, since, until) and published and has_new_version
                and updated > published + timedelta(hours=1)):
            return {
                "event_at": updated.isoformat(timespec="seconds"),
                "event_label": "arXiv 版本更新",
                "is_new_paper": False,
            }
        return None
    if provider == "openreview":
        # OpenReview tmdate can change because of reviews/discussion metadata;
        # without explicit evidence, do not treat that as a paper update.
        if _in_window(published, since, until):
            return {
                "event_at": published.isoformat(timespec="seconds"),
                "event_label": "新论文 / 新投稿",
                "is_new_paper": True,
            }
        return None

    if provider == "github":
        if _in_window(published, since, until):
            event = updated if _in_window(updated, since, until) else published
            label = "新建代码库"
        elif _in_window(updated, since, until):
            event, label = updated, "代码库近期提交"
        else:
            return None
    elif provider == "huggingface":
        if _in_window(published, since, until):
            event = updated if _in_window(updated, since, until) else published
            label = "新建模型仓库"
        elif _in_window(updated, since, until):
            event, label = updated, "模型仓库近期更新"
        else:
            return None
    else:
        if _in_window(published, since, until):
            event, label = published, "机构新发布"
        elif _in_window(updated, since, until):
            event, label = updated, "机构页面近期更新"
        else:
            return None

    return {
        "event_at": event.isoformat(timespec="seconds"),
        "event_label": label,
        "is_new_paper": False,
    }


def score_candidate(item, event_at, now=None):
    """Return topic-match score (0-10) and evidence-based reasons; never a quality grade."""
    provider = str(item.get("discovered_from") or "").lower()
    title = str(item.get("title") or "")
    tag_values = []
    for key in ("tags", "github_topics", "hf_tags"):
        value = item.get(key, [])
        if isinstance(value, list):
            tag_values.extend(map(str, value))
    text = " ".join(
        [title, str(item.get("description") or ""), str(item.get("abstract") or ""),
         " ".join(tag_values), str(item.get("hf_pipeline_tag") or ""),
         str(item.get("hf_library_name") or "")]
    ).lower()

    if any(term in text for term in NOISE_TERMS):
        return {"match_score": 0.0, "match_reasons": ["疑似自动生成或测试仓库，已降权"], "relevant": False}

    source_points = {
        "arxiv": 2.2, "openreview": 2.1, "institution": 1.8,
        "official-feeds": 1.8, "github": 1.25, "huggingface": 1.0,
    }.get(provider, 0.7)
    points = source_points
    reasons = ["来源：" + SOURCE_LABELS.get(provider, provider or "未知")]

    matched_topics = []
    for key, label, terms, weight in TOPIC_GROUPS:
        if any(term in text for term in terms):
            points += weight
            matched_topics.append((key, label))
            reasons.append("主题：" + label)

    if not matched_topics:
        return {"match_score": 0.0, "match_reasons": ["未命中核心研究主题"], "relevant": False}

    if any(term in text for term in EFFICIENCY_TERMS):
        points += 0.9
        reasons.append("方法关键词：高效化 / 压缩 / 低成本训练")
    if any(term in text for term in ARTIFACT_TERMS):
        points += 0.35
        reasons.append("成果类型：Benchmark / 数据集 / 评测")

    if provider == "github":
        description = str(item.get("description") or "").strip()
        stars = int(item.get("github_stars") or 0)
        if description:
            points += 0.25
        if stars >= 10:
            points += 0.35
            reasons.append(f"社区信号：{stars} stars")
        if item.get("github_license"):
            points += 0.15
            reasons.append("仓库提供许可证元数据")
        if "github_stars" in item and not description and stars == 0 and not item.get("github_topics"):
            points -= 0.7
            reasons.append("仓库描述与社区信号不足")

    if provider == "huggingface":
        downloads = int(item.get("hf_downloads") or 0)
        likes = int(item.get("hf_likes") or 0)
        has_card = item.get("hf_has_model_card")
        tags = item.get("hf_tags") if isinstance(item.get("hf_tags"), list) else []
        if downloads >= 100 or likes >= 5:
            points += 0.45
            reasons.append("模型仓库有一定下载 / 点赞信号")
        if has_card is False and downloads < 5 and likes == 0:
            points -= 2.0
            reasons.append("模型卡与社区使用信号不足")
        if (re.search(r"20\d{6}", title) and downloads < 10 and likes == 0
                and has_card is not True):
            points -= 3.5
            reasons.append("名称疑似批量生成的日期标记")
        if (downloads == 0 and likes == 0 and has_card is not True
                and not item.get("hf_pipeline_tag") and not item.get("hf_library_name")):
            points -= 2.0
            reasons.append("模型卡、任务标签与社区使用信号不足")

    now = now or datetime.now(timezone.utc)
    age_hours = max(0.0, (now - event_at).total_seconds() / 3600)
    if age_hours <= 24:
        points += 1.0
        reasons.append("时间：近24小时")
    elif age_hours <= 24 * 7:
        points += 0.65
        reasons.append("时间：近7天")

    return {
        "match_score": round(min(10.0, max(0.0, points)), 1),
        "match_reasons": reasons[:5],
        "relevant": True,
    }


def candidate_priority(item, event):
    """Prefer new research publications, then evidence-rich research artifacts."""
    provider = str(item.get("discovered_from") or "").lower()
    if provider in PAPER_SOURCES and event.get("is_new_paper"):
        return 0
    if provider == "arxiv" and event.get("event_label") == "arXiv 版本更新":
        return 1
    if provider in {"institution", "official-feeds"}:
        return 2
    if provider == "huggingface":
        downloads = int(item.get("hf_downloads") or 0)
        likes = int(item.get("hf_likes") or 0)
        if item.get("hf_has_model_card") is True or downloads >= 100 or likes >= 5:
            return 2
        if item.get("hf_pipeline_tag") or item.get("hf_library_name"):
            return 3
        return 5
    if provider == "github":
        stars = int(item.get("github_stars") or 0)
        description = str(item.get("description") or "").strip()
        text = " ".join([
            str(item.get("title") or ""), description,
            " ".join(map(str, item.get("github_topics", []))) if isinstance(item.get("github_topics"), list) else "",
        ]).lower()
        research_terms = (
            "benchmark", "dataset", "token compression", "token reduction",
            "quantization", "distillation", "lora", "qlora", "vision-language",
            "vision language", "document-vlm", "video-language", "evaluation",
            "document rag", "video rag", "model compression", "inference engine",
            "vlm fine-tuning", "vlm fine tuning", "document retrieval",
        )
        if stars >= 10 and description and item.get("github_license"):
            return 2
        if any(term in text for term in research_terms):
            return 3
        if description and stars >= 5:
            return 4
        return 5
    return 5


def rank_candidates(items, since, until, limit=15, threshold=3.5):
    """Rank current-window leads by topic match and recency; all remain unreviewed."""
    ranked = []
    for item in items:
        if not isinstance(item, dict) or item.get("review") != "pending":
            continue
        if not valid_url(item.get("source_url")):
            continue
        event = candidate_event(item, since, until)
        if not event:
            continue
        event_at = _date(event["event_at"])
        if not event_at:
            continue
        scored = score_candidate(item, event_at, until)
        if not scored["relevant"] or scored["match_score"] < threshold:
            continue
        ranked.append({
            "id": item.get("id", ""),
            "title": item.get("title", ""),
            "category": item.get("category", ""),
            "source_url": item["source_url"],
            "paper_url": item.get("paper_url"),
            "pdf_url": item.get("pdf_url"),
            "abstract": item.get("abstract") or "",
            "authors": item.get("authors") if isinstance(item.get("authors"), list) else [],
            "venue": item.get("venue") or "",
            "arxiv_categories": item.get("arxiv_categories") if isinstance(item.get("arxiv_categories"), list) else [],
            "github_url": item.get("github_url"),
            "huggingface_url": item.get("huggingface_url"),
            "description": item.get("description") or item.get("abstract") or "",
            "github_stars": item.get("github_stars"),
            "github_license": item.get("github_license"),
            "hf_downloads": item.get("hf_downloads"),
            "hf_likes": item.get("hf_likes"),
            "hf_has_model_card": item.get("hf_has_model_card"),
            "hf_pipeline_tag": item.get("hf_pipeline_tag"),
            "hf_library_name": item.get("hf_library_name"),
            "github_topics": item.get("github_topics", []),
            "priority_tier": candidate_priority(item, event),
            "discovered_from": item.get("discovered_from", ""),
            "published_at": item.get("published_at"),
            "updated_at": item.get("updated_at"),
            "event_at": event["event_at"],
            "event_label": event["event_label"],
            "is_new_paper": event["is_new_paper"],
            "match_score": scored["match_score"],
            "match_reasons": scored["match_reasons"],
            "review": "pending",
        })
    ranked.sort(key=lambda x: (
        x.get("priority_tier", 5), -x["match_score"],
        -(_date(x["event_at"]) or datetime.min.replace(tzinfo=timezone.utc)).timestamp(),
        x.get("id", ""),
    ))
    return ranked if limit is None else ranked[:max(0, limit)]


def summarize_candidates(items, since, until, threshold=3.5):
    ranked = rank_candidates(items, since, until, limit=None, threshold=threshold)
    category_counts = {}
    source_counts = {}
    for item in ranked:
        category_counts[item.get("category", "unknown")] = category_counts.get(item.get("category", "unknown"), 0) + 1
        source_counts[item.get("discovered_from", "unknown")] = source_counts.get(item.get("discovered_from", "unknown"), 0) + 1
    return {
        "window_start": since.isoformat(timespec="seconds"),
        "window_end": until.isoformat(timespec="seconds"),
        "relevant_count": len(ranked),
        "new_papers_count": sum(1 for item in ranked if item.get("is_new_paper")),
        "category_counts": category_counts,
        "source_counts": source_counts,
        "selection_threshold": threshold,
        "selection_note": "Rule-based topic relevance only; not a scientific-quality score or human approval.",
    }
