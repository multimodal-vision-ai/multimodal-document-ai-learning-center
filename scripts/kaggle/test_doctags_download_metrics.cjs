"use strict";
const assert = require("node:assert/strict");
(async () => {
  const {createDownloadMeter,formatBytes,formatRate,formatEta} = await import("../../docs/assets/projects/doctags/browser-inference/adapters/r3-ovisocr3/download-metrics.mjs");
  let clock = 0;
  const meter = createDownloadMeter(() => clock);
  let m = meter.update({status:"progress_total",stage:"model",loaded:0,total:1000,progress:0});
  assert.equal(m.progress,0); assert.equal(m.bytesPerSecond,0);
  clock = 1000;
  m = meter.update({status:"progress_total",stage:"model",loaded:500,total:1000,progress:50});
  assert.equal(m.progress,50); assert.equal(m.bytesPerSecond,500); assert.equal(m.etaSeconds,1);
  clock = 2000;
  m = meter.update({status:"progress_total",stage:"model",loaded:900,total:1000,progress:90});
  assert.equal(m.progress,90); assert.ok(m.bytesPerSecond > 400 && m.bytesPerSecond < 500);
  assert.ok(m.etaSeconds > 0 && m.etaSeconds < 1);
  clock = 2500;
  m = meter.update({status:"progress_total",stage:"processor",loaded:100,total:200,progress:50});
  assert.equal(m.stage,"processor"); assert.equal(m.bytesPerSecond,0);
  clock = 3000;
  m = meter.update({status:"progress_total",stage:"processor",loaded:200,total:200,progress:100});
  assert.equal(m.progress,100); assert.equal(m.etaSeconds,0);
  assert.equal(meter.update({status:"progress",stage:"model",loaded:10,total:100}),null);
  assert.equal(formatBytes(2520000000),"2.52 GB");
  assert.equal(formatRate(3150000),"3.15 MB/s");
  assert.equal(formatRate(0),"测速中");
  assert.equal(formatEta(65),"1 分 5 秒");
  assert.equal(formatEta(3605),"1 小时 0 分");
  console.log("Download metrics tests: aggregate progress, stage reset, throughput smoothing, ETA and formatting PASS");
})().catch(error => { console.error(error); process.exitCode = 1; });
